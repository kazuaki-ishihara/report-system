/**
 * チャットに入れた文の判定（G-25 §2.6。チャット（faq_answer_chat()）と自動入力検証（tools/test/faq_input_check.php）が使う。記録・数えることはしない）。
 * 判定の順: 命・体の緊急の状態（§2.12。119 番を案内） → 心の不調らしい文（§2.8） → 自分の退職（§2.10。寄り添って上司への相談を促す）
 *   → 要配慮個人情報に触れる文（§2.9） → 人への暴力を書いた文 → 不適切な表現 → 呼びかけだけの文 → 曖昧な質問 → 関係のない質問 → 近い質問を探す。
 * 心の不調らしい文は、心配な言葉の段階なら近い質問も探して一緒に返す（「助けて、ログインできない」など）。
 *
 * @param array<int, array<string, int|float|string|null>> $faqList 聞いた人に見えるよくある質問
 * @return array{code: string, matches: array<int, array<string, int|float|string|null>>, distressLevel: string, noticeLevel: string, harassmentBySuperior: bool}
 *   code: emergency・distress・retirement・sensitive・sabotage（システム・データを壊す）・violence（人への暴力）・abusive・opener（呼びかけだけ）・closing（用件がない）・vague・unrelated・matched・no_match。
 *   noticeLevel: 管理者に知らせる理由（心の不調の段階 → sabotage（システム・データを壊す） → violence（人への暴力） → credential（K-057） → retirement（K-054）。なければ空）
 */
/**
 * 前置き（「すみません、」「あの、」「えっと、」）と結びのあいさつ（「よろしくお願いします。」）を外す（APP-100）。
 * 付けても知りたいことは変わらないので、判定の前に外す。前置きは区切り（読点・空白など）が続くときだけ外す（「あのボタン」の「あの」は外さない）。
 * 外すと何も残らない文（「すみません」「よろしくお願いします」だけ）は、そのまま返す。
 */
function faq_strip_courtesy(string $questionText): string
{
    $strippedText = trim($questionText);
    $separatorPattern = '[、,，。.．\s\x{3000}!！ー〜~…]+';
    $prefixPattern = '/^(すみません(が)?|すいません(が)?|済みません(が)?|恐れ入ります(が)?|失礼します|あのう?|あのー+|えっと|えーっと|えーと|ええと)' . $separatorPattern . '/u';
    $suffixPattern = '/[、,，。.．\s\x{3000}]*(どうぞ)?(よろしく|宜しく)(お願い|おねがい)?(します|いたします|致します|申し上げます)?[。.．!！\s\x{3000}]*$/u';
    do {
        $previousText = $strippedText;
        $strippedText = trim((string) preg_replace($prefixPattern, '', $strippedText));
        $strippedText = trim((string) preg_replace($suffixPattern, '', $strippedText));
    } while ($strippedText !== $previousText && $strippedText !== '');
    return $strippedText === '' ? trim($questionText) : $strippedText;
}

/** 英語の文と見るときの、よく使う英語の言葉（faq_is_foreign_language()） */
const FAQ_ENGLISH_COMMON_WORDS = ['who', 'what', 'how', 'where', 'when', 'why', 'which', 'is', 'are', 'can', 'could', 'do', 'does', 'did', 'the', 'a', 'an', 'it',
    'i', 'my', 'me', 'you', 'please', 'help', 'in', 'to', 'of', 'for', 'with', 'not', 'cannot', 'account', 'settings', 'setting', 'english', 'language', 'japanese'];

/** 日本語の文には出てこない、中国語の言い回し（かなの無い文に、これが 1 つでもあれば中国語の文とみなす） */
const FAQ_CHINESE_ONLY_WORDS = ['可以', '我的', '你', '吗', '嗎', '什么', '什麼', '怎么', '怎麼', '请问', '請問', '顯示', '显示', '能不能', '是不是', '没有', '沒有', '這', '这', '們', '们', '語言', '语言'];

/**
 * 日本語以外の言葉の文か（2026-11-18。K-060）。次のどれか。
 * - 英語など、ラテン文字の文: 日本語の文字が無く、言葉が 2 つ以上で、よく使う英語の言葉（FAQ_ENGLISH_COMMON_WORDS）があるか、
 *   言葉が 3 つ以上で「?」で終わる文（「Who is the system administrator?」「account settings」、フィジー語などの問い）
 * - ハングル・デーヴァナーガリー・タイ文字・アラビア文字・キリル文字などがある文（かなが無いとき）
 * - かなが無く、中国語の言い回し（FAQ_CHINESE_ONLY_WORDS）がある文（「可以用我的語言顯示嗎？」）
 * 「PDF」「excel csv」「Hello World!」のような短い英字や、漢字だけの日本語（「臨時調査」「月次」）は当たらない。
 */
function faq_is_foreign_language(string $queryText): bool
{
    $trimmedText = trim($queryText);
    // 入力の全体で言い換える言葉（「Q&A」「Chrome」など）は、英語の文として扱わない
    if (isset(FAQ_WHOLE_INPUT_SYNONYMS[str_replace(' ', '', faq_normalize_text($queryText))])) {
        return false;
    }
    if (preg_match('/[\p{Hiragana}\p{Katakana}]/u', $trimmedText) === 1) {
        return false;
    }
    if (preg_match('/[\p{Hangul}\p{Devanagari}\p{Thai}\p{Arabic}\p{Cyrillic}\p{Hebrew}\p{Bengali}\p{Tamil}\p{Greek}]/u', $trimmedText) === 1) {
        return true;
    }
    foreach (FAQ_CHINESE_ONLY_WORDS as $chineseWord) {
        if (strpos($trimmedText, $chineseWord) !== false) {
            return true;
        }
    }
    // ラテン文字（アクセント付きを含む）だけの文
    if (preg_match('/\A[\x00-\x7F\x{00C0}-\x{024F}\x{1E00}-\x{1EFF}\x{FF01}-\x{FF5E}\x{3000}？！。、]+\z/u', $trimmedText) !== 1) {
        return false;
    }
    preg_match_all('/[a-z\x{00C0}-\x{024F}\x{1E00}-\x{1EFF}]+/u', mb_strtolower(faq_normalize_text($trimmedText), 'UTF-8'), $wordMatchList);
    $latinWordList = $wordMatchList[0];
    if (count($latinWordList) >= 2 && array_intersect($latinWordList, FAQ_ENGLISH_COMMON_WORDS) !== []) {
        return true;
    }
    return count($latinWordList) >= 3 && preg_match('/[?？]\z/u', $trimmedText) === 1;
}

function faq_classify_question(string $questionText, array $faqList): array
{
    // 前置き・結びのあいさつは、判定の前に外す（APP-100）
    $questionText = faq_strip_courtesy($questionText);
    $matchedFaqList = [];
    $distressLevel = faq_distress_level($questionText);
    if (faq_is_emergency($questionText)) {
        // 命・体の緊急の状態: 119 番を案内する（心の不調の言葉も入っていれば、知らせる）
        $resultCode = 'emergency';
    } elseif ($distressLevel !== 'urgent' && faq_is_sabotage($questionText)) {
        // システムやデータを壊す・消す・持ち出すつもりの文: 答えずに、できないことを返す（断った回数には数えない。下でシステム管理者・補佐に知らせる。2026-11-18）
        $resultCode = 'sabotage';
    } elseif (faq_is_condition_insult($questionText)) {
        // 心の病気の名前で人をけなす文: 心の不調・要配慮ではなく、不適切な表現（2026-11-18）
        $resultCode = 'abusive';
        $distressLevel = '';
    } elseif ($distressLevel !== '') {
        $resultCode = 'distress';
        // 心配な言葉で、ほかにはっきり知りたいことがあるときだけ、その答えも出す（「助けて、ログインできない」。「仕事を辞めたい」の「仕事」のような弱い当たりは出さない）
        $matchedFaqList = $distressLevel === 'concern' ? faq_companion_matches(faq_strip_distress_words($questionText), $faqList) : [];
    } elseif (faq_is_retirement($questionText) && !faq_is_about_subordinate($questionText)) {
        // 自分の退職: 手続きは示さず、寄り添って上司（課長）への相談を促す（部下の退職は、下で手続きの答えを探す。どちらも管理者に知らせる）
        $resultCode = 'retirement';
    } elseif (faq_is_sensitive($questionText)) {
        // 要配慮個人情報に触れる文: 寄り添う返事。ほかにはっきり知りたいことがあれば、その答えも出す（「入院するので報告が出せない」）
        $resultCode = 'sensitive';
        $matchedFaqList = faq_companion_matches(faq_strip_sensitive_words($questionText), $faqList);
    } elseif (faq_is_violent($questionText)) {
        // 人への暴力を書いた文: 答えは出さず、カウンセリングを受けることをすすめる（断らない。下でシステム管理者・補佐に知らせる。2026-11-17 指示）
        $resultCode = 'violence';
    } elseif (faq_is_abusive($questionText)) {
        $resultCode = 'abusive';
    } elseif (faq_is_opener($questionText)) {
        // 呼びかけだけ（「大変です」）: 用件を聞き返す。断らない（断った回数に数えない）
        $resultCode = 'opener';
    } elseif (faq_is_closing($questionText)) {
        // 用件がない（「用件なし」「大丈夫です」）: 聞き返さずに受け止める。断らない
        $resultCode = 'closing';
    } elseif (faq_is_foreign_language($questionText) && !faq_has_strong_offtopic_word($questionText) && ($englishFaqList = faq_search('日本語以外 英語 表示 言語', $faqList)) !== []) {
        // 日本語以外の言葉の文: 断らずに、日本語だけであること・日本語で聞いてほしいことを（英語も添えて）答える（2026-11-18。K-060）
        $resultCode = 'matched';
        $matchedFaqList = array_slice($englishFaqList, 0, 1);
        // 日本語以外で聞かれたときだけ、日本語で聞いてほしいことを（英語も添えて）先に書く。日本語で聞いた人には付けない（「質問は日本語で入れたぞ」）
        $matchedFaqList[0]['answer'] = '質問は日本語で入れてください。' . "
" . 'Please ask your question in Japanese. This system and this chat are available in Japanese only.' . "
" . $matchedFaqList[0]['answer'];
    } elseif (faq_is_company_policy_question($questionText)) {
        // 勤務時間・手当など会社の決まりの質問: よくある質問では答えられない。見つからないとして、課長・確認者への相談・質問として送る案内を出す
        $resultCode = 'no_match';
    } elseif (faq_is_vague($questionText)) {
        $resultCode = 'vague';
    } elseif (faq_is_unrelated($questionText, $faqList)) {
        $resultCode = 'unrelated';
    } else {
        $matchedFaqList = faq_search($questionText, $faqList);
        $resultCode = $matchedFaqList ? 'matched' : 'no_match';
        // 亡くなったと書かれたときだけ、いちばんの答えにお悔やみを添える（答えの文には書かない。逃げた・交代しただけかもしれないので決めつけない）
        if ($matchedFaqList && faq_mentions_death($questionText) && strpos((string) $matchedFaqList[0]['answer'], 'お悔やみ') === false) {
            $matchedFaqList[0]['answer'] = '心よりお悔やみ申し上げます。' . "\n" . $matchedFaqList[0]['answer'];
        }
        // 言語の答えで、日本語が分からない・読めないと書かれたときは、英語の案内も先に付ける（日本語で書かれていても。2026-11-18。K-060）
        if ($matchedFaqList && strpos((string) $matchedFaqList[0]['question'], '日本語以外で表示できるか') !== false
            && preg_match('/日本語(は|が|も)?(わから|分から|わかん|読めな|よめな|苦手|にがて|できな|出来な|無理|むり)/u', str_replace([' ', '　'], '', $questionText)) === 1) {
            $matchedFaqList[0]['answer'] = 'This system and this chat are available in Japanese only. If you cannot read Japanese, please ask your section manager or a coworker for help.' . "\n" . $matchedFaqList[0]['answer'];
        }
    }
    // 知らせる理由: 心の不調らしい文の段階 → 人への暴力（violence） → ID・パスワードを求める質問（credential。K-057） → 退職に関わる質問（retirement。K-054）
    $noticeLevel = $resultCode === 'sabotage' && $distressLevel !== 'urgent' ? 'sabotage' : $distressLevel;
    if ($noticeLevel === '' && faq_is_violent($questionText)) {
        $noticeLevel = 'violence';
    } elseif ($noticeLevel === '' && faq_is_credential_request($questionText)) {
        $noticeLevel = 'credential';
    } elseif ($noticeLevel === '' && !in_array($resultCode, ['abusive', 'violence'], true) && faq_is_retirement($questionText)) {
        $noticeLevel = 'retirement';
    }
    // 上司からのハラスメント: 心の不調の返事を、ほかの管理職・相談窓口への相談をすすめる文にする
    $isHarassmentBySuperior = $resultCode === 'distress' && faq_is_harassment_by_superior($questionText);
    return ['code' => $resultCode, 'matches' => $matchedFaqList, 'distressLevel' => $distressLevel, 'noticeLevel' => $noticeLevel,
            'harassmentBySuperior' => $isHarassmentBySuperior];
}

// ---- 会話（G-25 §2.14。2026-11-17 指示: 複数の発言を一つの会話として扱う） ----
/** 同じ人の発言を 1 つの会話とみなす間隔（秒）。これより空いたら新しい会話にする */
const FAQ_CONVERSATION_GAP_SECONDS = 600;
/** 会話の話題として覚える文の長さ（文字。長い文は先頭だけ） */
const FAQ_CONVERSATION_TOPIC_MAX_LENGTH = 100;
/**
 * 「心の不調の会話」の印（話題の代わりに覚える。2026-11-17）。命に関わる言葉・緊急の状態の文があった会話では、
 * 続く文（「もう実行するって決めた」「止めてくれる人がいない」など、1 文だけでは見分けにくい言い方）を断らず、気づかいの返事を続ける
 */
const FAQ_CONVERSATION_DISTRESS_MARK = '#distress';
/** 心の不調の会話の印が続く発言の数（命に関わる文のあと、この回数まで。命に関わる文がまた出れば、数え直す） */
const FAQ_CONVERSATION_DISTRESS_TURNS = 3;

/** 話題が心の不調の会話の印なら、残りの発言の数（印でなければ 0） */
function faq_conversation_distress_turns_left(string $topicText): int
{
    if (preg_match('/\A' . preg_quote(FAQ_CONVERSATION_DISTRESS_MARK, '/') . ':(\d+)\z/', $topicText, $turnMatch) !== 1) {
        return 0;
    }
    return (int) $turnMatch[1];
}

/**
 * 会話の中での判定。今の発言だけでは中身がない（曖昧な質問）とき、同じ会話の直前の話題とつなげて探し、答えが見つかればそれを返す。
 * 話題にするのは、答えた・見つからなかった発言だけ（緊急・心の不調・要配慮・暴力・関係のない質問などの文は話題にしない）。
 * チャット（faq_answer_chat()）と自動入力検証（tools/test/faq_input_check.php）が使う。記録・セッションには触れない。
 *
 * @param array<int, array<string, int|float|string|null>> $faqList 聞いた人に見えるよくある質問
 * @return array{classification: array, contextTopic: string, nextTopic: string}
 *   classification: faq_classify_question() と同じ形。contextTopic: 前の話題を補って答えたときの話題（補っていなければ空）。nextTopic: 次の発言で使う話題
 */
function faq_classify_in_conversation(string $questionText, string $previousTopic, array $faqList): array
{
    $classification = faq_classify_question($questionText, $faqList);
    $contextTopic = '';
    // 心の不調の会話（命に関わる文のあと FAQ_CONVERSATION_DISTRESS_TURNS 回の発言まで）: 続く文が、関係のない質問・あいまい・見つからない・
    // 弱い当たりなら、断らずに気づかいの返事（心配な言葉の段階）にする。はっきり当たる答えがある文には、ふつうに答える。
    // 指示を引き出そうとする入力は、会話にかかわらず断る
    $distressTurnsLeft = faq_conversation_distress_turns_left($previousTopic);
    $remainingDistressMark = $distressTurnsLeft > 1 ? FAQ_CONVERSATION_DISTRESS_MARK . ':' . ($distressTurnsLeft - 1) : '';
    if ($classification['code'] === 'emergency' || ($classification['code'] === 'distress' && $classification['distressLevel'] === 'urgent')) {
        return ['classification' => $classification, 'contextTopic' => '', 'nextTopic' => FAQ_CONVERSATION_DISTRESS_MARK . ':' . FAQ_CONVERSATION_DISTRESS_TURNS];
    }
    if ($distressTurnsLeft > 0) {
        $hasClearAnswer = $classification['code'] === 'matched' && $classification['matches'] !== []
            && (float) ($classification['matches'][0]['match_ratio'] ?? 0) >= FAQ_DISTRESS_COMPANION_MIN_RATIO;
        if (in_array($classification['code'], ['unrelated', 'vague', 'no_match', 'matched', 'opener', 'abusive'], true)
            && !$hasClearAnswer && !faq_has_strong_offtopic_word($questionText)) {
            $classification['code'] = 'distress';
            $classification['distressLevel'] = 'concern';
            $classification['noticeLevel'] = $classification['noticeLevel'] === '' ? 'concern' : $classification['noticeLevel'];
            $classification['matches'] = faq_companion_matches($questionText, $faqList);
            $classification['harassmentBySuperior'] = false;
        }
        return ['classification' => $classification, 'contextTopic' => '', 'nextTopic' => $remainingDistressMark];
    }
    // 前の話題そのものの答えを出す（つなげた文で探し直すと、中身のない言葉で弱い答えに当たるため）。
    // 返事への聞き返し（「どういうこと？」「はい？」）には補わない（同じ答えをくり返しても役に立たないため）
    if ($classification['code'] === 'vague' && $previousTopic !== '' && !faq_is_clarification($questionText) && faq_has_followup_word($questionText)) {
        $topicClassification = faq_classify_question($previousTopic, $faqList);
        if ($topicClassification['code'] === 'matched') {
            $classification = $topicClassification;
            $contextTopic = $previousTopic;
        }
    }
    $nextTopic = $previousTopic;
    if ($contextTopic === '' && in_array($classification['code'], ['matched', 'no_match'], true)) {
        $topicCharacterList = preg_split('//u', trim($questionText), -1, PREG_SPLIT_NO_EMPTY) ?: [];
        $nextTopic = implode('', array_slice($topicCharacterList, 0, FAQ_CONVERSATION_TOPIC_MAX_LENGTH));
    } elseif ($contextTopic === '' && $classification['code'] !== 'vague') {
        // 緊急・心の不調・関係のない質問などのあとは、前の話題を持ち越さない。
        // 呼びかけ（「もしもし」「大変です」）のあとも、話が切り替わるので持ち越さない（古い話題の答えをくり返さないように）
        $nextTopic = '';
    }
    return ['classification' => $classification, 'contextTopic' => $contextTopic, 'nextTopic' => $nextTopic];
}

/**
 * 今の会話（セッションに持つ）。前の発言から FAQ_CONVERSATION_GAP_SECONDS 秒より空いていれば、新しい会話を始める。
 *
 * @return array{id: string, topic: string}
 */
function faq_conversation_current(): array
{
    $conversation = $_SESSION['faq_conversation'] ?? null;
    if (!is_array($conversation) || time() - (int) ($conversation['last_at'] ?? 0) > FAQ_CONVERSATION_GAP_SECONDS) {
        $conversation = ['id' => bin2hex(random_bytes(8)), 'topic' => '', 'last_at' => time()];
    }
    $conversation['last_at'] = time();
    $_SESSION['faq_conversation'] = $conversation;
    return ['id' => (string) $conversation['id'], 'topic' => (string) $conversation['topic']];
}

/** 続きを聞く言い方（あいまいな文のうち、これが入っているときだけ、同じ会話の前の話題を補う。2026-11-17） */
const FAQ_FOLLOWUP_WORDS = ['どうすれば', 'どうしたら', 'どうやって', 'どうする', 'どうな', '教えて', 'おしえて', 'やり方', 'やりかた', '方法', '続き', '詳しく', 'くわしく',
    'もっと', 'どこ', 'いつ', 'なんで', 'なぜ', 'どうして', 'それ', 'その', '具体的', '手順', '聞きたい', 'どれ', 'どの'];

/** 続きを聞く言い方が入っているか */
function faq_has_followup_word(string $questionText): bool
{
    $normalizedQuery = faq_normalize_text($questionText);
    foreach (FAQ_FOLLOWUP_WORDS as $followupWord) {
        if (strpos($normalizedQuery, $followupWord) !== false) {
            return true;
        }
    }
    return false;
}

/** 返事への聞き返し（前の話題を補わない）。faq_normalize_text() でそろえ、空白を除いた文がこれだけでできているとき */
const FAQ_CLARIFICATION_PHRASES = ['どういうこと', 'どういう意味', '意味がわからない', '意味が分からない', 'はい', 'え', 'えっ', 'なに', '何', 'どういう違い', 'なんでやねん', 'これも',
    'じゃけん', 'だけん', 'やけん', 'じゃけ', 'やけ', 'けん', 'じゃん', 'やん', 'だべ', 'やで', 'ばい', 'なぁ', 'なあ', 'そうなんよ', 'そうなんですね', 'そうなんですか'];

/** 返事への聞き返しか（「どういうこと？」「はい？」） */
function faq_is_clarification(string $questionText): bool
{
    $compactText = str_replace(' ', '', faq_normalize_text($questionText));
    foreach (FAQ_CLARIFICATION_PHRASES as $clarificationPhrase) {
        $compactText = str_replace($clarificationPhrase, '', $compactText);
    }
    return $compactText === '' && trim(faq_normalize_text($questionText)) !== '';
}

/** 「解決しない」のあとに出す、関係がありそうな質問の数 */
const FAQ_RELATED_MAX_COUNT = 5;

/**
 * 関係がありそうな質問（「解決しない」を押したとき。G-25 §2.15）。
 * 答えた質問の文で近い質問を探し、足りなければ同じ分野の質問で補う。出した質問（$excludedFaqIdList）は除く。
 *
 * @param array<int, array<string, int|float|string|null>> $faqList 見せてよい質問
 * @param int[] $excludedFaqIdList
 * @return array<int, array<string, int|float|string|null>>
 */
function faq_related_entries(array $faqList, int $baseFaqId, array $excludedFaqIdList): array
{
    $baseFaqRow = null;
    foreach ($faqList as $faqRow) {
        if ((int) $faqRow['id'] === $baseFaqId) {
            $baseFaqRow = $faqRow;
            break;
        }
    }
    if ($baseFaqRow === null) {
        return [];
    }
    $excludedIdSet = array_flip(array_merge([$baseFaqId], array_map('intval', $excludedFaqIdList)));
    $relatedFaqList = [];
    $candidateList = array_merge(faq_search((string) $baseFaqRow['question'], $faqList), faq_in_category($faqList, (string) $baseFaqRow['category']));
    foreach ($candidateList as $candidateRow) {
        $candidateId = (int) $candidateRow['id'];
        if (isset($excludedIdSet[$candidateId])) {
            continue;
        }
        $excludedIdSet[$candidateId] = true;
        $relatedFaqList[] = $candidateRow;
        if (count($relatedFaqList) >= FAQ_RELATED_MAX_COUNT) {
            break;
        }
    }
    return $relatedFaqList;
}

